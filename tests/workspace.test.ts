import { test,after } from 'node:test';
import assert from 'node:assert/strict';
import { database,createAgent,getAgent,listAgents,saveProgress,connectDemo,refreshDemo,disconnectDemo } from '../lib/db';
import { safeConfig,demoResult,PROVIDERS } from '../lib/providers';
process.env.DATABASE_PATH='memory://';
after(async()=>{await (await database()).close()});
test('complete demo lifecycle persists partial success and prevents duplicate provisioning',async()=>{
 const a=await createAgent('owner-a','Test agent','Integration test');
 assert.equal(a.name,'Test agent');
 await saveProgress('owner-a',a.id,3,['coinbase','crossmint','link']);
 await connectDemo('owner-a',a.id,'coinbase','success');
 await connectDemo('owner-a',a.id,'crossmint','failure');
 await connectDemo('owner-a',a.id,'link','pending');
 let stored=(await getAgent('owner-a',a.id))!;
 assert.equal(stored.step,3);assert.equal(JSON.parse(stored.selected).length,3);
 assert.equal(stored.wallets.find(w=>w.provider==='coinbase')?.status,'connected');
 assert.equal(stored.wallets.find(w=>w.provider==='crossmint')?.status,'setup_failed');
 assert.equal(stored.wallets.find(w=>w.provider==='link')?.status,'authorization_pending');
 await Promise.all([connectDemo('owner-a',a.id,'crossmint','success'),connectDemo('owner-a',a.id,'crossmint','success')]);
 await connectDemo('owner-a',a.id,'link','success');
 stored=(await getAgent('owner-a',a.id))!;assert.equal(stored.wallets.length,3);assert.ok(stored.wallets.every(w=>w.status==='connected'));
 assert.equal(stored.wallets.find(w=>w.provider==='link')?.address,null);
 assert.equal(stored.wallets.find(w=>w.provider==='link')?.kind,'linked_payment_account');
 assert.equal(typeof stored.wallets[0].balance,'string');
 await refreshDemo('owner-a',a.id,'coinbase');
 const exported=safeConfig(stored);assert.equal(exported.mode,'demo');assert.equal(exported.simulated,true);assert.equal(exported.authorizesSpending,false);
 const json=JSON.stringify(exported);assert.ok(!/secret|ciphertext|accessToken|apiKey/.test(json));assert.equal(JSON.parse(json).providers.length,3);
 assert.equal(await getAgent('owner-b',a.id),null);assert.equal((await listAgents('owner-b')).length,0);
 await assert.rejects(connectDemo('owner-b',a.id,'coinbase','success'));
 await assert.rejects(disconnectDemo('owner-b',a.id,'coinbase'));
 await disconnectDemo('owner-a',a.id,'coinbase');stored=(await getAgent('owner-a',a.id))!;assert.equal(stored.wallets.length,2);assert.match(stored.activities[0].summary,/No external wallet/);
 await connectDemo('owner-a',a.id,'coinbase','success');assert.equal((await getAgent('owner-a',a.id))!.wallets.length,3);
});
test('demo adapters are deterministic and provider capabilities stay distinct',()=>{assert.deepEqual(demoResult('same','coinbase'),demoResult('same','coinbase'));assert.notEqual(demoResult('a','coinbase').address,demoResult('b','coinbase').address);assert.equal(PROVIDERS.link.kind,'Payment account');assert.ok(!PROVIDERS.link.capabilities.includes('Create wallet' as never));});
